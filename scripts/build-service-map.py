"""Builds components/service-map-data.ts: the Emerald Coast outline for the service-area map.

Coastline: GSHHS full resolution (pip install basemap basemap-data-hires).
County lines: US Census cartographic boundary counties, 1:500k (2018), passed as argv[1] GeoJSON.
Run: python3 scripts/build-service-map.py county500k.json
"""
import json, math, sys
from mpl_toolkits.basemap import Basemap
from shapely.geometry import Polygon, box, shape, mapping, LineString, MultiLineString
from shapely.ops import unary_union

W, S, E, N = -86.95, 30.315, -86.22, 30.56   # Navarre to Sandestin, Gulf to Niceville
VW = 1000

def merc(lon, lat):
    return math.radians(lon), math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))

x0, y1 = merc(W, N); x1, y0 = merc(E, S)
k = VW / (x1 - x0)
VH = round((y1 - y0) * k, 1)

def pr(lon, lat):
    x, y = merc(lon, lat)
    return (x - x0) * k, (y1 - y) * k

m = Basemap(llcrnrlon=W - 0.3, llcrnrlat=S - 0.2, urcrnrlon=E + 0.3, urcrnrlat=N + 0.2,
            resolution="f", projection="cyl")
frame = box(-2, -2, VW + 2, VH + 2)
land = []
for (xs, ys), lvl in zip(m.coastpolygons, m.coastpolygontypes):
    if lvl != 1:
        continue
    p = Polygon([pr(x, y) for x, y in zip(xs, ys)]).buffer(0)
    if p.intersects(frame):
        land.append(p.intersection(frame))
land = unary_union(land).simplify(0.35, preserve_topology=True)

def d_of(geom):
    out = []
    polys = [geom] if geom.geom_type == "Polygon" else list(geom.geoms)
    for p in polys:
        if p.geom_type != "Polygon" or p.area < 4:
            continue
        for ring in [p.exterior, *p.interiors]:
            pts = list(ring.coords)[:-1]
            out.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z")
    return "".join(out)

def line_d(geom):
    lines = [geom] if geom.geom_type == "LineString" else [g for g in getattr(geom, "geoms", []) if g.geom_type == "LineString"]
    return "".join("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in l.coords) for l in lines if l.length > 6)

counties = {}
for f in json.load(open(sys.argv[1]))["features"]:
    p = f["properties"]
    if p.get("STATEFP") == "12" and p["NAME"] in ("Okaloosa", "Walton", "Santa Rosa"):
        g = shape(f["geometry"])
        polys = [g] if g.geom_type == "Polygon" else list(g.geoms)
        counties[p["NAME"]] = unary_union([Polygon([pr(*c[:2]) for c in q.exterior.coords]) for q in polys])

def border(a, b):
    shared = counties[a].boundary.intersection(counties[b].boundary.buffer(0.6))
    return line_d(shared.intersection(land.buffer(-0.5)).simplify(0.4))

towns = {
    "fort-walton-beach": (-86.6188, 30.4058),
    "destin": (-86.4958, 30.3935),
    "navarre": (-86.8636, 30.4016),
    "niceville": (-86.4822, 30.5169),
    "mary-esther": (-86.6655, 30.4099),
    "shalimar": (-86.5786, 30.4458),
    "valparaiso": (-86.5025, 30.4927),
    "bluewater-bay": (-86.4294, 30.4846),
    "miramar-beach": (-86.3586, 30.3744),
    "sandestin": (-86.3260, 30.3830),
    "wright": (-86.6383, 30.4557),
    "ocean-city": (-86.6127, 30.4413),
    "wynnehaven-beach": (-86.7680, 30.4054),
}
pts = {s: tuple(round(v, 1) for v in pr(*ll)) for s, ll in towns.items()}

out = f"""// Generated by scripts/build-service-map.py. Do not edit by hand.
// Coastline: GSHHS full resolution. County lines: US Census 1:500k. Web Mercator, {W},{S} to {E},{N}.
export const MAP_W = {VW};
export const MAP_H = {VH};
export const landPath = "{d_of(land)}";
export const countyLines = {{
  santaRosaOkaloosa: "{border('Santa Rosa', 'Okaloosa')}",
  okaloosaWalton: "{border('Okaloosa', 'Walton')}",
}};
export const townPoints: Record<string, [number, number]> = {json.dumps({s: list(v) for s, v in pts.items()})};
"""
open("components/service-map-data.ts", "w").write(out)
print(VH, len(out), pts)
